const SERIES_EXCERPT = `function harmonics(wave: WaveType, N: number) {
  const out: { k: number; a: number }[] = [];
  for (let k = 1; k <= N; k++) {
    let a = 0;
    if (wave === "square") {
      if (k % 2 === 1) a = 4 / Math.PI / k;
    } else if (wave === "sawtooth") {
      a = ((2 / Math.PI) * (k % 2 === 0 ? -1 : 1)) / k;
    } else if (wave === "triangle") {
      if (k % 2 === 1) {
        const m = (k - 1) / 2;
        a = ((8 / (Math.PI * Math.PI)) * (m % 2 === 0 ? 1 : -1)) / (k * k);
      }
    }
    out.push({ k, a });
  }
  return out;
}

function partialSum(harms, t) {
  let s = 0;
  for (const { k, a } of harms) s += a * Math.sin(k * 2 * Math.PI * t);
  return s;
}`;

